// mcpInstructions is what the server tells the client about using adder, as docs/agents.md does.
const mcpInstructions = `adder generates and maintains the repeated parts of this Go repository, declared in adder.yaml.

- To add a component, use a generator instead of writing its files by hand: list them with the list tool, read one's inputs with describe, and see what it would create with preview.
- Never edit a file whose header says "Code generated by adder ... DO NOT EDIT." It is rewritten from its template; use explain to find the template, and change that instead.
- After changing code that a derived file depends on, run check, and derive when it reports outputs out of date.
- Fix every warning about something deprecated, as it says.`

func newMCPCommand(opts *globalOptions) *cobra.Command {
	var write bool
	cmd := &cobra.Command{
		Use:   "mcp",
		Short: "Serve adder's commands to coding agents over MCP",
		Long: `mcp serves the Model Context Protocol over standard input and output, so a coding agent calls adder's
commands as tools: list, describe, explain, check, test, and preview. With --write, it also offers derive and a
tool for each generator, which write files. Start it from the agent's configuration as go tool adder mcp.`,
		Args: usageArgs(cobra.NoArgs),
		RunE: func(cmd *cobra.Command, _ []string) error {
			transport := &mcp.IOTransport{Reader: io.NopCloser(cmd.InOrStdin()), Writer: nopWriteCloser{cmd.OutOrStdout()}}
			return newMCPServer(opts, write).server.Run(cmd.Context(), transport)
		},
	}
	cmd.Flags().BoolVar(&write, "write", false, "also offer derive and a tool for each generator, which write files")
	return cmd
}

type nopWriteCloser struct{ io.Writer }

func (nopWriteCloser) Close() error { return nil }

// mcpServer serves adder's commands as MCP tools, each one running the command as adder itself would.
type mcpServer struct {
	opts   *globalOptions
	write  bool
	server *mcp.Server

	writing    sync.Mutex // writing tools run one at a time
	refreshing sync.Mutex
	generators map[string]string // the generator tools registered now, by name, with their input schemas
}

func newMCPServer(opts *globalOptions, write bool) *mcpServer {
	m := &mcpServer{opts: opts, write: write, generators: map[string]string{}}
	m.server = mcp.NewServer(&mcp.Implementation{Name: "adder", Version: opts.version}, &mcp.ServerOptions{Instructions: mcpInstructions})
	read := &mcp.ToolAnnotations{ReadOnlyHint: true, OpenWorldHint: new(false)}

	tool(m, "list", "List the generators and derived outputs in adder.yaml, as adder list.", `{}`, nil, read,
		func(struct{}) ([]string, []byte, error) { return []string{"list"}, nil, nil })
	tool(m, "describe", "Describe a generator: its inputs, with a JSON Schema for them, its files, and its message, as adder describe.",
		`{"generator": {"type": "string", "description": "The generator's name."}}`, []string{"generator"}, read,
		func(a struct{ Generator string }) ([]string, []byte, error) {
			return []string{"describe", "--", a.Generator}, nil, nil
		})
	tool(m, "explain", "Say which output and template produce a file, and whether it is up to date, as adder explain.",
		`{"path": {"type": "string", "description": "The file, relative to the repository root."}}`, []string{"path"}, read,
		func(a struct{ Path string }) ([]string, []byte, error) {
			return []string{"explain", "--", m.fromRoot(a.Path)}, nil, nil
		})
	tool(m, "check", "Report derived outputs that are out of date, without writing anything, as adder check.",
		`{"diff": {"type": "boolean", "description": "Also give each out-of-date output's unified diff."}}`, nil, read,
		func(a struct{ Diff bool }) ([]string, []byte, error) {
			return withDiff([]string{"check"}, a.Diff), nil, nil
		})
	tool(m, "test", "Run generators' tests against their golden files, as adder test.",
		`{"generators": {"type": "array", "items": {"type": "string"}, "description": "The generators to test; all of them when left out."}}`, nil, read,
		func(a struct{ Generators []string }) ([]string, []byte, error) {
			return append([]string{"test", "--"}, a.Generators...), nil, nil
		})
	tool(m, "preview", "Show the files a generator would create and the derived outputs it would change, without writing anything, as adder new --dry-run.",
		`{"generator": {"type": "string", "description": "The generator's name."}, "inputs": {"type": "object", "description": "The generator's inputs, by name, as describe's inputSchema gives them."}, "diff": {"type": "boolean", "description": "Also give each file's content as a unified diff."}}`,
		[]string{"generator"}, read,
		func(a struct {
			Generator string
			Inputs    map[string]any
			Diff      bool
		}) ([]string, []byte, error) {
			if err := generatorName(a.Generator); err != nil {
				return nil, nil, err
			}
			if a.Inputs == nil {
				a.Inputs = map[string]any{}
			}
			inputs, err := json.Marshal(a.Inputs)
			return withDiff([]string{"new", a.Generator, "--inputs", "-", "--dry-run"}, a.Diff), inputs, err
		})
	if write {
		tool(m, "derive", "Update every derived output, writing the changes and removing outputs no longer produced, as adder derive.", `{}`, nil,
			&mcp.ToolAnnotations{DestructiveHint: new(true), IdempotentHint: true, OpenWorldHint: new(false)},
			func(struct{}) ([]string, []byte, error) { return []string{"derive"}, nil, nil })
	}
	m.server.AddReceivingMiddleware(func(next mcp.MethodHandler) mcp.MethodHandler {
		return func(ctx context.Context, method string, req mcp.Request) (mcp.Result, error) {
			if method == "tools/list" || method == "tools/call" {
				m.refresh()
			}
			return next(ctx, method, req)
		}
	})
	m.refresh()
	return m
}

// tool registers a fixed tool. properties and required describe its arguments, which args decodes and turns into
// the adder command line to run, and the standard input to give it.
func tool[A any](m *mcpServer, name, description, properties string, required []string, annotations *mcp.ToolAnnotations, args func(A) ([]string, []byte, error)) {
	schema := fmt.Sprintf(`{"type": "object", "properties": %s, "required": %s, "additionalProperties": false}`, properties, jsonList(required))
	m.server.AddTool(&mcp.Tool{Name: name, Description: description, InputSchema: json.RawMessage(schema), Annotations: annotations},
		func(ctx context.Context, req *mcp.CallToolRequest) (*mcp.CallToolResult, error) {
			var a A
			if raw := req.Params.Arguments; len(raw) > 0 {
				if err := strictJSON(raw, &a); err != nil {
					return toolError("invalid arguments: %v", err), nil
				}
			}
			line, stdin, err := args(a)
			if err != nil {
				return toolError("%v", err), nil
			}
			return m.run(ctx, annotations.ReadOnlyHint, line, stdin), nil
		})
}

// refresh registers a tool for each generator in adder.yaml as it is now, with --write, and removes the tools of
// generators that are gone. The SDK tells the client when the list changes.
func (m *mcpServer) refresh() {
	if !m.write {
		return
	}
	m.refreshing.Lock()
	defer m.refreshing.Unlock()
	o := *m.opts
	o.warnings = nil // the tools report warnings in their results
	want := map[string]string{}
	descriptions := map[string]string{}
	if cfg, _, err := o.load(); err == nil {
		for name, gen := range cfg.Generators {
			schema, _ := json.Marshal(scaffold.StaticInputSchema(gen))
			want["new-"+name] = string(schema)
			descriptions["new-"+name] = strings.TrimSpace(fmt.Sprintf("%s Creates its files and updates derived outputs, as adder new %s.", gen.Description, name))
			if gen.Deprecated != "" {
				descriptions["new-"+name] += " Deprecated: " + gen.Deprecated
			}
		}
	}
	var gone []string
	for name, schema := range m.generators {
		if want[name] != schema {
			gone = append(gone, name)
		}
	}
	if len(gone) > 0 {
		m.server.RemoveTools(gone...)
	}
	for _, name := range slices.Sorted(maps.Keys(want)) {
		if m.generators[name] == want[name] {
			continue
		}
		generator := strings.TrimPrefix(name, "new-")
		m.server.AddTool(&mcp.Tool{
			Name:        name,
			Description: descriptions[name],
			InputSchema: json.RawMessage(want[name]),
			Annotations: &mcp.ToolAnnotations{DestructiveHint: new(false), OpenWorldHint: new(false)},
		}, func(ctx context.Context, req *mcp.CallToolRequest) (*mcp.CallToolResult, error) {
			inputs := []byte(req.Params.Arguments)
			if len(inputs) == 0 {
				inputs = []byte("{}")
			}
			return m.run(ctx, false, []string{"new", generator, "--inputs", "-"}, inputs), nil
		})
	}
	m.generators = want
}

// run runs adder with line, the command and its arguments, and returns what it prints with --format json. The
// result is an error when adder found problems, but not when outputs are only out of date.
func (m *mcpServer) run(ctx context.Context, readOnly bool, line []string, stdin []byte) *mcp.CallToolResult {
	if !readOnly {
		m.writing.Lock()
		defer m.writing.Unlock()
	}
	var global []string
	if m.opts.root != "" {
		global = append(global, "--root", m.opts.root)
	}
	if m.opts.config != "" {
		global = append(global, "--config", m.opts.config)
	}
	global = append(global, "--format", formatJSON)
	// Global flags go before a -- that ends the command's own.
	args := []string{line[0]}
	args = append(args, global...)
	args = append(args, line[1:]...)
	var out bytes.Buffer
	code := Main(ctx, m.opts.version, m.opts.packList, args, bytes.NewReader(stdin), &out, io.Discard)
	return &mcp.CallToolResult{
		Content:           []mcp.Content{&mcp.TextContent{Text: out.String()}},
		StructuredContent: json.RawMessage(bytes.TrimSpace(out.Bytes())),
		IsError:           code == ExitError || code == ExitUsage,
	}
}

// fromRoot returns path, which an agent gives relative to the repository root, as adder reads it from the current
// directory. A path that is absolute, or that cannot be placed because adder.yaml does not load, is left for adder
// to report on.
func (m *mcpServer) fromRoot(path string) string {
	o := *m.opts
	o.warnings = nil
	if _, root, err := o.load(); err == nil && !filepath.IsAbs(path) {
		return filepath.Join(root, filepath.FromSlash(path))
	}
	return path
}

func toolError(format string, a ...any) *mcp.CallToolResult {
	return &mcp.CallToolResult{Content: []mcp.Content{&mcp.TextContent{Text: fmt.Sprintf(format, a...)}}, IsError: true}
}

// generatorName rejects a generator name that adder would read as a flag.
func generatorName(name string) error {
	if name == "" || strings.HasPrefix(name, "-") {
		return fmt.Errorf("generator %q is not a generator's name", name)
	}
	return nil
}

func withDiff(line []string, diff bool) []string {
	if diff {
		return append(line, "--diff")
	}
	return line
}

func strictJSON(data []byte, v any) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	return dec.Decode(v)
}

func jsonList(list []string) string {
	if list == nil {
		return "[]"
	}
	data, _ := json.Marshal(list)
	return string(data)
}
